export type TranslationKey = keyof typeof translations['uz'];

export function getTranslation(lang: Language, key: TranslationKey, fallback?: string): string {
  const dict = translations[lang] || translations.uz;
  const val = (dict as Record<string, string>)[key];
  if (val) return val;
  const uzVal = (translations.uz as Record<string, string>)[key];
  if (uzVal) return uzVal;
  return fallback || key;
}

export function useTranslation() {
  const { language, setLanguage } = useLanguage();
  const t = (key: TranslationKey, fallback?: string): string => {
    return getTranslation(language, key, fallback);
  };
  return { language, setLanguage, t, strings: translations[language] || translations.uz };
}

/**
 * Client component to render translated text dynamically inside Server or Client components.
 */
export function T({ k, fallback }: { k: TranslationKey; fallback?: string }) {
  const { language } = useLanguage();
  return React.createElement(React.Fragment, null, getTranslation(language, k, fallback));
}

/**
 * Client component to render an input with dynamic translated placeholder inside Server or Client components.
 */
export function LocalizedInput({
  placeholderKey,
  className,
  defaultValue,
  name,
  type = 'text',
  ...props
}: {
  placeholderKey: TranslationKey;
  className?: string;
  defaultValue?: string;
  name?: string;
  type?: string;
  [key: string]: any;
}) {
  const { language } = useLanguage();
  const placeholder = getTranslation(language, placeholderKey);
  return React.createElement('input', {
    ...props,
    type,
    name,
    defaultValue,
    placeholder,
    className,
  });
}
